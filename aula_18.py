# == ------------- igual a ----------------- 2 == 2
# != ------------- diferente de -------------- 2 != 3
# > -------------- maior que ---------------- 3 > 2
# < -------------- menor que ---------------- 2 < 3
# >= ------------- maior ou igual a --------- 3 >= 3
# <= ------------- menor ou igual a -------- 2 <= 3

maior = 2 > 1
maior_ou_igual = 2 >= 2
menor = 1 < 2
menor_ou_igual = 1 <= 2
